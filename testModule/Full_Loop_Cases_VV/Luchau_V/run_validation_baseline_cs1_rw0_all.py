def _list_arg(values: list[float]) -> str:
    return ",".join(f"{value:g}" for value in values)


def run_case(case: dict[str, object]) -> None:
    power = float(case["power"])
    validation_dir = validation_directory(power)
    log_path = validation_dir / "results" / "baseline_cs1_rw0_stdout.log"
    cmd = [
        sys.executable,
        str(SCRIPT),
        "--thermal-power-kwt", f"{power:g}",
        "--wire-resistance-ohm", "0",
        "--cesium-pressure-torr", "1",
        "--voltage-list", _list_arg(case["voltages"]),
        "--target-current-list", _list_arg(case["currents"]),
        "--workers", "16",
        "--force-first-run",
    ]
    print(f"[baseline] start {power:g} kW; log={log_path}", flush=True)
    validation_dir.joinpath("results").mkdir(parents=True, exist_ok=True)
    with log_path.open("w", encoding="utf-8") as log:
        process = subprocess.Popen(cmd, cwd=str(REPO_ROOT), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
        assert process.stdout is not None
        for line in process.stdout:
            print(line, end="", flush=True)
            log.write(line)
            log.flush()
        code = process.wait()
    if code != 0:
        raise subprocess.CalledProcessError(code, cmd)
    print(f"[baseline] done {power:g} kW", flush=True)


def main() -> int:
    for case in CASES:
        run_case(case)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
